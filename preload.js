const { contextBridge, ipcRenderer, webUtils } = require('electron')

contextBridge.exposeInMainWorld('sb', {
  cfg: () => ipcRenderer.invoke('cfg:get'),
  salvarCfg: (c) => ipcRenderer.invoke('cfg:set', c),
  chats: () => ipcRenderer.invoke('chats:get'),
  salvarChats: (c) => ipcRenderer.invoke('chats:set', c),
  escolherPasta: () => ipcRenderer.invoke('pasta:escolher'),
  enviar: (p) => ipcRenderer.invoke('chat:enviar', p),
  parar: (id) => ipcRenderer.invoke('chat:parar', id),
  aoDelta: (fn) => ipcRenderer.on('chat:delta', (_e, d) => fn(d)),
  aoFim: (fn) => ipcRenderer.on('chat:fim', (_e, d) => fn(d)),
  routerEstado: () => ipcRenderer.invoke('router:estado'),
  api: (metodo, rota, corpo) => ipcRenderer.invoke('router:api', { metodo, rota, corpo }),
  modelos: () => ipcRenderer.invoke('modelos:listar'),
  abrirExterno: (url) => ipcRenderer.invoke('externo:abrir', url),
  anexar: (p) => ipcRenderer.invoke('anexo:salvar', p),
  caminhoDe: (arquivo) => webUtils.getPathForFile(arquivo),
  abrirArquivo: (p) => ipcRenderer.invoke('arquivo:abrir', p),
  mostrarArquivo: (p) => ipcRenderer.invoke('arquivo:mostrar', p),
  lerArquivo: (p) => ipcRenderer.invoke('arquivo:ler', p),
  abrirLogs: () => ipcRenderer.invoke('logs:abrir'),
  info: () => ipcRenderer.invoke('app:info'),
  responderPermissao: (req, resposta) => ipcRenderer.invoke('chat:permissao-resp', { req, resposta }),
  aoPermissao: (fn) => ipcRenderer.on('chat:permissao', (_e, d) => fn(d)),
  skills: {
    listar: () => ipcRenderer.invoke('skills:listar'),
    ler: (r) => ipcRenderer.invoke('skills:ler', r),
    gravar: (r, c) => ipcRenderer.invoke('skills:gravar', r, c),
    criar: (n, c) => ipcRenderer.invoke('skills:criar', n, c),
    apagar: (r) => ipcRenderer.invoke('skills:apagar', r),
    renomear: (r, n) => ipcRenderer.invoke('skills:renomear', r, n),
    copiar: (r) => ipcRenderer.invoke('skills:copiar', r),
    buscar: (t) => ipcRenderer.invoke('skills:buscar', t),
    historico: (r) => ipcRenderer.invoke('skills:historico', r),
    versao: (r, h) => ipcRenderer.invoke('skills:versao', r, h),
    aoMudar: (fn) => ipcRenderer.on('skills:mudou', (_e, d) => fn(d)),
    repo: {
      estado: () => ipcRenderer.invoke('skillsrepo:estado'),
      vincular: (url, tok) => ipcRenderer.invoke('skillsrepo:vincular', url, tok),
      desvincular: () => ipcRenderer.invoke('skillsrepo:desvincular'),
      loginDisponivel: () => ipcRenderer.invoke('skillsrepo:login-disponivel'),
      loginIniciar: () => ipcRenderer.invoke('skillsrepo:login-iniciar'),
      loginAguardar: (o) => ipcRenderer.invoke('skillsrepo:login-aguardar', o),
      criar: (n) => ipcRenderer.invoke('skillsrepo:criar', n),
      sincronizar: (o) => ipcRenderer.invoke('skillsrepo:sincronizar', o),
    },
  },
  remoto: {
    estado: () => ipcRenderer.invoke('remoto:estado'),
    ativar: (s) => ipcRenderer.invoke('remoto:ativar', s),
    vincular: () => ipcRenderer.invoke('remoto:vincular'),
    revogar: (id) => ipcRenderer.invoke('remoto:revogar', id),
    placa: () => ipcRenderer.invoke('remoto:placa'),
    placaNova: () => ipcRenderer.invoke('remoto:placa-nova'),
    eventos: () => ipcRenderer.invoke('remoto:eventos'),
    responder: (m) => ipcRenderer.invoke('remoto:responder', m),
    aoEstado: (fn) => ipcRenderer.on('remoto:estado', (_e, d) => fn(d)),
    aoComando: (fn) => ipcRenderer.on('remoto:cmd', (_e, d) => fn(d)),
  },
  exportarDados: () => ipcRenderer.invoke('dados:exportar'),
  importarDados: () => ipcRenderer.invoke('dados:importar'),
  unlimitedEstado: () => ipcRenderer.invoke('unlimited:estado'),
  unlimitedRecusar: () => ipcRenderer.invoke('unlimited:recusar'),
  unlimitedEntrar: (email, senha) => ipcRenderer.invoke('unlimited:entrar', { email, senha }),
  unlimitedEsqueci: (email) => ipcRenderer.invoke('unlimited:esqueci', email),
  unlimitedSair: () => ipcRenderer.invoke('unlimited:sair'),
  aoUnlimited: (fn) => ipcRenderer.on('unlimited:estado', (_e, d) => fn(d)),
  ditadoModelo: () => ipcRenderer.invoke('ditado:modelo'),
  navegador: {
    limites: (l) => ipcRenderer.invoke('navegador:limites', l),
    mostrar: (sim) => ipcRenderer.invoke('navegador:mostrar', sim),
    esconderTemp: (sim) => ipcRenderer.invoke('navegador:esconder-temp', sim),
    acao: (acao, url) => ipcRenderer.invoke('navegador:acao', { acao, url }),
    estado: () => ipcRenderer.invoke('navegador:estado'),
    favoritos: () => ipcRenderer.invoke('navegador:favoritos'),
    importarFavoritos: () => ipcRenderer.invoke('navegador:importar-favoritos'),
    favoritar: (f) => ipcRenderer.invoke('navegador:favoritar', f),
    aoEstado: (fn) => ipcRenderer.on('navegador:estado', (_e, d) => fn(d)),
    aoAbrirPainel: (fn) => ipcRenderer.on('navegador:abrir-painel', () => fn()),
  },
  aoErro: (fn) => ipcRenderer.on('chat:erro', (_e, d) => fn(d)),
})
