// Ajuste dos prazos das ferramentas do app no Hermes instalado (spec 37)
const test = require('node:test')
const assert = require('node:assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { ajustarHermes } = require('../agent')

test('troca só o texto exato, uma vez, e não mexe em versão diferente', () => {
  const raiz = fs.mkdtempSync(path.join(os.tmpdir(), 'herm-'))
  const dir = path.join(raiz, 'hermes-agent', 'gateway')
  fs.mkdirSync(dir, { recursive: true })
  const f = path.join(dir, 'session_local_mcp.py')
  fs.writeFileSync(f, 'x\n        config.update(connect_timeout=5, tool_timeout=30, lazy=False)\ny\n')
  assert.strictEqual(ajustarHermes(raiz), 'ajustado')
  assert.match(fs.readFileSync(f, 'utf8'), /connect_timeout=20, tool_timeout=900/)
  assert.strictEqual(ajustarHermes(raiz), 'ja')
  fs.writeFileSync(f, 'config.update(connect_timeout=8, tool_timeout=60)\n')
  assert.strictEqual(ajustarHermes(raiz), 'sem-alvo')
  assert.strictEqual(ajustarHermes(path.join(raiz, 'nao-existe')), 'sem-arquivo')
})
